import fs from 'node:fs';
const root=import.meta.dirname;
let html=fs.readFileSync(root+'/dist/index.html','utf8');
const css=fs.readFileSync(root+'/dist/styles.css','utf8')+'\n'+fs.readFileSync(root+'/dist/v2.css','utf8')+'\n'+fs.readFileSync(root+'/dist/v3.css','utf8');
const model=fs.readFileSync(root+'/dist/model.js','utf8').replaceAll('export ','');
const app=fs.readFileSync(root+'/dist/app-v2.js','utf8').replace(/^import .*?;\r?\n/gm,'');
const exportsCode=fs.readFileSync(root+'/dist/exports.js','utf8').replaceAll('export ','');
const stripModule=s=>s.replace(/^import .*?;\r?\n/gm,'').replaceAll('export ','');
const settingsCode=stripModule(fs.readFileSync(root+'/dist/export-settings.js','utf8'));
const exportCode=stripModule(fs.readFileSync(root+'/dist/exports.js','utf8'));
const uiCode=stripModule(fs.readFileSync(root+'/dist/export-ui.js','utf8'));
const combined=model+'\n'+settingsCode+'\n'+exportCode+'\n'+uiCode+'\n'+app;
new Function(combined);
const inline=s=>s.replace(/<\/script/gi,'<\\/script');
html=html.replace('<link rel="stylesheet" href="styles.css">',()=>`<style>${css}</style>`).replace('<link rel="stylesheet" href="v2.css">','').replace('<link rel="stylesheet" href="v3.css">','');
for(const name of ['catalog-data.js','branding-assets.js','vendor/docx.js','vendor/pdf-lib.js','vendor/fontkit.js','vendor/fonts.js'])html=html.replace(`<script src="${name}"></script>`,()=>`<script>${inline(fs.readFileSync(root+'/dist/'+name,'utf8'))}</script>`);
html=html.replace('<script type="module" src="app-v2.js"></script>',()=>`<script type="module">${inline(combined)}</script>`);
fs.writeFileSync(root+'/Studieplanering.html',html);
console.log('Skapad: Studieplanering.html');
